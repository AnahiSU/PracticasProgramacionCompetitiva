#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n; cin>>n;
   vector<int>v(n);
   for(int i =0; i<n;i++) cin>>v[i];

   int k = 0;
   srt(v);
   for(int i = 0; i<n;i++){
      if(k+1>=v[i]){
         k += v[i];
      }else{
         break;
      }
   }
   cout<<k+1<<endl;

   return 0;
}

