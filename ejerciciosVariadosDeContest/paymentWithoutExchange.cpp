using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){
		int a,b,n,s; cin>>b>>a>>n>>s;
		int nec = s/n;

		if(nec<=b){
			nec=n*(nec);
		}else{
			nec=b*n;
		}

		if(a+nec >= s){
			cout<<"YES";
		}else{
			cout<<"NO";
		}
		cout<<endl;
	}
    return 0;
}

