#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n,m; cin>>n>>m;
      vector<int>v(n*m);
      for(int i = 0; i<n;i++){
         for(int j = 0; j<m;j++){
            int x; cin>>x;
            v[x] = i;
         }
      }

      bool flag = 1;
      for(int i = 0; i<n;i++){
         for(int j = i;j<n*m;j+=n){
            if(v[i] != v[j]){
               flag = 0;
            }
         }
      }

      if(!flag){
         cout<<-1<<endl;
      }else{
         for(int i = 0; i<n; i++){
            cout<<v[i]+1<<' ';
         }
         cout<<endl;
      }
      
   }
   return 0;
}

