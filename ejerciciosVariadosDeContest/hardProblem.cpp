signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){
		int m,a,b,c; cin>>m>>a>>b>>c;
		int res = 0;
		int r1 = m,r2 = m;
		if(r1>=a){
			r1-=a;
			res+=a;
		}else{
			res+=r1;
			r1=0;
		}
		if(r2>=b){
			r2-=b;
			res+=b;
		}else{
			res+=r2;
			r2=0;
		}

		if(r1>=c){
			res+= c;
			c = 0;
		}else{
			res+= r1;
			c -=r1;
		}

		if(c){
			if(r2>=c){
				res += c;
			}else{
				res+= r2;
			}
		}
		cout<<res<<endl;
	}
    return 0;
}

