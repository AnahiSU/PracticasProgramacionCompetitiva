using namespace std;

signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){
		int n,k; cin>>n>>k;
		int sum = 0,maxi = -1;
		for(int i =0 ; i<n;i++){
			int x; cin>>x;
			sum+=x;
			maxi = max(maxi,x);
		}

		cout<<max((sum+k-1)/k , maxi)<<endl;
	}
    return 0;
}

