#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n;  cin>>n;
      vector<int> v(n+1);
      for(int i = 1; i <= n; i++) cin >>v[i];
      int b = (2*v[1]-v[2])/(n+1);
      int a = v[1] - n*b;
      if (a < 0 || b < 0) {
         cout<<"NO"<<endl;
         continue;
      }
      bool flag = 1;
      for(int i = 1; i <= n; i++){
         if (v[i] != (a*i) + b*(n-i+1)) {
            flag = 0;   
            cout<<"NO"<<endl;
            break;
         }
      }
      if(flag)cout<<"YES"<<endl;

   }
   return 0;
}

