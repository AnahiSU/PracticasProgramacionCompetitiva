#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      map<int,int>ls;
      for(int i = 0; i<n;i++){
         int x; cin>>x;
         ls[x]++;
      }
      if(sz(ls) == 1 || n<=3 && sz(ls)<=2){
         cout<<"YES"<<endl;
      }else{
         bool flag = 1;
         for(auto i : ls){
            if(i.second > 1) flag = 0;
         }

         if(flag) cout<<"YES"<<endl;
         else cout<<"NO"<<endl;

      }
   }
   return 0;
}

