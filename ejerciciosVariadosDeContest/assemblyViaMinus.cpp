#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      int a = (n*(n-1))/2;
      vector<int>v(a);
      for(int i = 0; i<a;i++){
         cin>>v[i];
      }
      srt(v);
      vector<int>res;
      int c = n;
      for(int i = 0; i<a;i+=c){
         res.push_back(v[i]);
         c--;
      }
      res.push_back(res.back());
      for(int i : res){
         cout<<i<<' ';
      }
      cout<<endl;
   }
   return 0;
}

