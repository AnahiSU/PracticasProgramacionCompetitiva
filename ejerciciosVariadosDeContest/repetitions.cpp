signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	string s; cin>>s;
	int n = s.size();
	char ant = 's';
	int cont  =0;
	int res = 0;
	for(int i = 0;i <n;i++){
		if(s[i]!=ant){
			res = max(cont,res);
			cont =1;
		}else{
			cont++;
		}
		ant = s[i];
	}
	res = max(res,cont);
	cout<<res<<endl;

    return 0;
}

