#define srt(a) sort(a.begin(),a.end());
#include <bits/stdc++.h>
#define int long long

using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){
		int n,l,r;
		cin>>n>>l>>r;
		vector<int>v(n);
		for(int i = 0; i<n;i++){
			cin>>v[i];
		}
		int i=0,j=0,sum=v[0],cont=0;
		while(i<n&&j<n){
			if(sum<l){
				j++;
				if(j<n) sum+=v[j];
			}else{
				if(sum<=r){
					cont++;
					j++;
					i=j;
					if(j<n) sum=v[j];
				}else{
					sum-=v[i];
					i++;
				}
			}
		}
		cout<<cont<<endl;
	}
    return 0;
}

