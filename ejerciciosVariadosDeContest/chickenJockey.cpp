#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()
using namespace std;
int MOD = 998244353;

signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n; cin>>n;
   vector<int>v(n+1),dp(n+1);
   unordered_map<int,int>ls;

   for(int i = 1; i<=n;i++){
      cin>>v[i];
   }
   dp[0] = 1;
   for(int i = 1; i<=n;i++){
      dp[i] = (dp[i-1] + ls[v[i]]) % MOD;
      ls[v[i]] = (ls[v[i]] + dp[i-1]) % MOD;
   }
   cout<<dp[n]<<endl;
   return 0;
}

