#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;

signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);

   int n;
   cin >> n;
   vector<pair<double, double>> dp(24);
   dp[1] = {100, 0};
   dp[2] = {0, 100};
   for (int i = 3; i <= 23; i++) {
      dp[i].first = (dp[i - 1].first + dp[i - 2].first) / 2;
      dp[i].second = (dp[i - 1].second + dp[i - 2].second) / 2;
   }
   cout << fixed << setprecision(9);
   cout << (dp[min(n, 23LL)].first) << ' ' << (dp[min(n, 23LL)].second) << '\n';

   return 0;
}

