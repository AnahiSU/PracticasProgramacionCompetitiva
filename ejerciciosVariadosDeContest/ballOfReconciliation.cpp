#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int x;
   while(cin>>x && x!=-1){
      int cont = 0;
      for(int i = 0; i<=x;i++){
         for(int j = 0; ((i+1)*(j-1))<=x;j++){
            if(i+j == 0) continue;
            int aux = (x-(i*j));
            if(aux % (i+j) == 0){
               int c = aux/(i+j);
               if(i>=j && j>=c) cont++;
            }
         }
      }
      cout<<cont<<endl;
   }
   return 0;
}

