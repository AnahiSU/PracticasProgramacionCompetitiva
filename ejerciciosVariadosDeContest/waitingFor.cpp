using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	int esp = 0;
	while(c--){
		char sign;
		int ind; cin>>sign>>ind;
		if(sign == 'P'){
			esp+=ind;
		}else{
			if(esp <= ind){
				if(abs(esp - ind)>=1){
					cout<<"YES"<<endl;
					esp=0;
				}else{
					esp -= ind;
					cout<<"NO"<<endl;
				}
			}else{
				esp-=ind;
				cout<<"NO"<<endl;
			}
		}
	}
    return 0;
}

