#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int p; cin>>p;
      vector<int>res(p);
      int cont = 2;
      int mid = p/2;
      
      res[mid] = p;


      for(int i = 0; i<p;i++){
         if(i == mid) continue;
         res[i] = cont;
         cont++;
      }
      res[p-1] = 1;
      for(int i : res){
         cout<<i <<' ';
      }
      cout<<endl;
   }
   return 0;
}

