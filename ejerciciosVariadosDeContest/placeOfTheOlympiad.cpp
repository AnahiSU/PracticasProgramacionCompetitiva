using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n,m,k; cin>>n>>m>>k;
      int l = -1, r = m;
      while(r-l>1){
         int mid = (l+r)/2;
         if((m / (mid + 1) * mid + m % (mid + 1)) * n >= k){
            r = mid;
         }else{
            l = mid;
         }
      }
      cout<<r<<endl;

   }
   return 0;
}

