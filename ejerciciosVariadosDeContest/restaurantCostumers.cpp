typedef long long ll;
#define srt(a) sort(a.begin(),a.end());
#include <bits/stdc++.h>


using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int n; cin>>n;
	vector<pair<int,int>>v;
	for(int i = 0; i<n;i++){
		int a,b; cin>>a>>b;
		v.push_back({a,1});
		v.push_back({b,-1});
		
	}
	srt(v);
	int c=0,maxi=0;
	for(int i = 0; i<2*n;i++){
		c+=v[i].second;
		maxi = max(c,maxi);
	}
	cout<<maxi<<endl;
    return 0;
}

