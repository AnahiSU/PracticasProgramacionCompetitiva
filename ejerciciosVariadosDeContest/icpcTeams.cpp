#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int a,b,c,n; cin>>n>>a>>b>>c;
   vector<int>v(n);
   for(int i = 0 ;i<n;i++) cin>>v[i];
   int res = 0;
   for(int i = 0; i<n;i++){
      res = max(res, (v[i]+a - 1 )/a);
      res = max(res, (v[i]+b-1)/b);
      res = max(res, (v[i]+c-1)/c);
   }

   cout<<res<<endl;
   return 0;
}

