#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      vector<int>v(n);
      for(int i = 0; i<n;i++) cin>>v[i];

      bool flag = 1;
      int ind =0;
      for(int i = 1; i<n;i++){
         if(v[i-1] > v[i]) ind = i;
      }
      for(int i = 0; i<ind-1;i++){
         int mini = min(v[i],v[i+1]);
         v[i]-=mini;
         v[i+1]-=mini;
      }

      for(int i = 1; i<n;i++){
         if(v[i-1] > v[i]) flag =0;
      }

      if(flag) cout<<"YES"<<endl;
      else cout<<"NO"<<endl;
   }
   return 0;
}

