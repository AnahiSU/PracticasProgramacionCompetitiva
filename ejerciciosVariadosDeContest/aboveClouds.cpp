#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      string s;cin>>s;
      map<char,int>ls;
      for(int i = 0; i<n;i++){
         ls[s[i]]++;
      }
      bool flag = 0;
      for(auto i : ls){
         if(i.second >1){
            if(i.first != s[0] || i.first!=s[n-1]){
               flag = 1;
               break;
            }else if(i.second > 2){
               flag = 1;
               break;
            }    
         }
      }
      if(flag || sz(ls)==1) cout<<"YES"<<endl;
      else cout<<"NO"<<endl;
   }
   return 0;
}

