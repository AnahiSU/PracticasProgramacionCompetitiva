signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n; cin>>n;
   int ev=0,od=0;
   for(int i = 0; i<n;i++){
      int x; cin>>x;
      if(x&1) od++;
      else ev++;
   }
   if(ev==od){
      cout<<"Notbastian"<<endl;
   }else{
      if(ev>od){
         cout<<"Sebastian"<<endl;
      }else{
         cout<<"Notbastian"<<endl;
      }
   }
   return 0;
}

