#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c;cin>>c;

   while(c--){
      bool flag = 1;
      int n; cin>>n;
      for(int i = 'a'; i<='z' && flag;i++){
         for(int j = 'a'; j<='z' && flag;j++){
            for(int k = 'a'; k<='z' && flag;k++){
               if(i-'a'+1+k-'a'+1+j-'a'+1 == n){
                  cout<<(char)i<<(char)j<<(char)k<<endl;
                  flag = 0;
                  break;
               }
            }
         }
      }
   }
   return 0;
}

