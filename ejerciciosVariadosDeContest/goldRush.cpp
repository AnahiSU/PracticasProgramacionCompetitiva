using namespace std;

bool buscar(int n,int m){
   if(n<m) return 0;
   if(n==m) return 1;
   if(n%3!=0) return 0; 
   return buscar(n/3,m) || buscar(2*(n/3),m);
}

signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n,m; cin>>n>>m;
      bool res = 0;
      if(n<m){
         res = 0;
      }else{
         res = buscar(n,m);  
      }
      if(res) cout<<"YES"<<endl;
      else cout<<"NO"<<endl;
   }
   return 0;
}

