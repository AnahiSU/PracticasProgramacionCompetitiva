#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n;
   while(cin>>n && n){
      string s; cin>>s;
      int cont = 0;
      int fil = sz(s)/n;
      vector<vector<char>>v(fil,vector<char>(n));

      for(int i = 0; i<fil;i++){
         for(int j = 0; j<n;j++){
            v[i][j] = s[cont];
            cont++;
         }
      }
      
      for(int i = 1; i<sz(v);i+=2){
         reverse(v[i].begin(),v[i].end());
      } 
      for(int i = 0; i<sz(v[0]);i++){
         for(int j = 0; j<sz(v);j++){
            cout<<v[j][i];
         }
      } 
      cout<<endl;
   }
   return 0;
}

