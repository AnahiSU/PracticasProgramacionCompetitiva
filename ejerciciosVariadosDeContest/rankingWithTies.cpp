#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n; cin>>n;
   vector<pair<int,int>>v(n);
   for(int i= 0; i<n;i++){
      int x; cin>>x;
      v[i] = {x,i};
   }
   sort(v.rbegin(),v.rend());
   vector<int>res(n); 
   int cont = 1,act = 1;
   res[v[0].second] = 1;
   for(int i = 1; i<n;i++){
      if(v[i-1].first == v[i].first){
         res[v[i].second] = act;
         cont++;
      }else{
         act+=cont;
         cont = 1;
         res[v[i].second] = act;
      }
   }
   for(int i : res){
      cout<<i<<endl;
   }
   
   return 0;
}

