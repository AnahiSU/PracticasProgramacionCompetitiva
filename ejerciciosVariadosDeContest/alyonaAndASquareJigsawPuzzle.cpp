using namespace std;
set<int>ls;
void preCalc(){
   int niv = 1;
   int sum = 1;
   while(sum<=10000){
      sum+= (niv*4) + 4;
      ls.insert(sum);
      niv+=2;
   }

}

signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   preCalc();
   while(c--){
      int n; cin>>n;
      int sum = 0,cont=1;
      for(int i = 0; i<n;i++){
         int x; cin>>x;
         sum+=x;
         if(ls.find(sum) != ls.end()) cont++;
      }
      cout<<cont<<endl;

   }
   return 0;
}

