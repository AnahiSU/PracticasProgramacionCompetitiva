#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      string s,t;cin>>s>>t;
      map<char,int>pos;
      for(int i = 0; i<sz(s);i++){
         pos[s[i]]=i+1;
      }
     
      int dis = 0;
      for(int i = 1; i<sz(t);i++){
         dis += abs(pos[t[i]] - pos[t[i-1]]);
      }
      cout<<dis<<endl;
   }
   return 0;
}

