using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n,q; cin>>n>>q;
   string server = "";
   vector<string>v(n);
   while(q--){
      int x; cin>>x;
      if(x==1){
         int p; cin>>p;
         v[p-1] = server;
      }else if(x==2){
         int p; cin>>p;
         string s; cin>>s;
         v[p-1] = v[p-1].append(s);
      }else{
         int p; cin>>p;
         server = v[p-1];
      }
   }
   cout<<server<<endl;
   return 0;
}

