#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      vector<int>v(n);
      for(int i = 0; i<n;i++) cin>>v[i];
      int res = 0;
      srt(v);
      if(n&1){
         int mini =v.front();
         for(int i = 1; i<n-1;i+=2){
            res += max(v[i],v[i+1]);
         }
         res+=mini;
      }else{
         for(int i = 0; i<n-1;i+=2){
            res += max(v[i],v[i+1]);
         }
      }
      //if(n&1)res+=v.back();
      cout<<res<<endl;
   }
   return 0;
}

