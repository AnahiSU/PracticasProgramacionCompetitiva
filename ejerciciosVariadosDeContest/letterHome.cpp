#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n,s; cin>>n>>s;
      vector<int>v(n);
      for(int i = 0; i<n;i++){
         cin>>v[i];
      }
      srt(v);
      if(v[0]>=s){
         cout<<abs(s-v[n-1])<<endl;
      }else if(v[n-1]<= s){
         cout<<abs(s-v[0])<<endl;
      }else{
         int dist1 = abs(v[0]-s);
         int dist2 = abs(v[n-1]-s);
         cout<<min(dist1,dist2)*2 + max(dist1,dist2)<<endl; 
      }
   }
   return 0;
}

