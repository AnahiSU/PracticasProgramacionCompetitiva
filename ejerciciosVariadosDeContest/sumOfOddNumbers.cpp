signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n,k; cin>>n>>k;
      if(k!=1){
         if(k&1 && n&1 && (int)pow(k,2)<=n){
            cout<<"YES"<<endl;
         }else{
            if(!(k&1) && !(n&1) && (int)pow(k,2)<=n){
               cout<<"YES"<<endl;
            }else{
               cout<<"NO"<<endl;
            }
         }
      }else{
         if(n&1 && (int)pow(k,2)<=n){
            cout<<"YES"<<endl;
         }else{
            cout<<"NO"<<endl;
         }
      }
   }
   return 0;
}

