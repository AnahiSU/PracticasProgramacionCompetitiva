#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      vector<int>v(n);
      for(int i = 0; i<n;i++) cin>>v[i];
      int maxi = *max_element(v.begin(),v.end());
      vector<int>res(n);
      int cont=0,cont2=0;
      for(int i = 0; i<n;i++){
         if(v[i] == maxi) {
            res[i] = 1;
            cont++;
         }else{
            res[i] = 2;
            cont2++;
         }
      }
      if(cont !=0 && cont2 != 0){
         cout<<"YES"<<endl;
         for(int i : res){
            cout<<i<<' ';
         }
         cout<<endl;
      }else{
         cout<<"NO"<<endl;
      }
   }
   return 0;
}

