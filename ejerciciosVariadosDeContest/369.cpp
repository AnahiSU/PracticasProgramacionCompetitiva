#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int a,b; cin>>a>>b;
   int q = -100000;
   int cont = 0;
   while(q<=100000){
      vector<int>v = {a,b,q};
      srt(v);
      if(v[2]-v[1] == v[1]-v[0]) cont++;
      q++;
   }
   cout<<cont<<endl;

   return 0;
}

