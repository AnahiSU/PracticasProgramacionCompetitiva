#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c;cin>>c;
   while(c--){
      int n; cin>>n;
      vector<int>v(n);
      for(int i = 0; i<n;i++) cin>>v[i];
      int maxi=-1, cont=0;
      for(int i = 0; i<n;i++){
         if(v[i] == 0){
            cont++;
         }else{
            maxi = max(maxi,cont);
            cont = 0;
         }
      }
      maxi = max(cont,maxi);
      cout<<maxi<<endl;
   }
   return 0;
}

