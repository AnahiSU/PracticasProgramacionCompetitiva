vector<string> append(vector<string>& m1, vector<string>& m2) {
   vector<string> ans(9, string(9, '.'));
   for (int i = 0; i < 9; i++) {
      for (int j = 0; j < 9; j++) {
         if (m1[i][j] != '.') {
            ans[i][j] = m1[i][j];
         }
         if (m2[i][j] != '.') {
            ans[i][j] = m2[i][j];
         }
      }
   }
   return ans;
}

