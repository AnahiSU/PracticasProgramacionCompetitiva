using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);

   int a, b, c;
   cin >> a >> b >> c;
   int ans = 0;
   while (a) {
      ans += 2;
      a--;
   }
   if (c >= 2) {
      if (b) {
         ans += 5 + 2 * (b - 1);
         b = 0;
         c--;
         ans += (c / 2) * 3;
      } else {
         ans += (c / 2) * 3;
      }
   } else {
      cout << ans << '\n';
      return 0;
   }
   cout << ans << '\n';


   return 0;
}

