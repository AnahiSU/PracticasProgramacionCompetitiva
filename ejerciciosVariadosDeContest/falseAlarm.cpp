#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;;
   while(c--){
      int n,k; cin>>n>>k;
      vector<int>v(n);
      for(int i = 0; i<n;i++) cin>>v[i];
      int cont = 0;
      bool flag = 1;
      for(int i = 0; i<n;i++){
         if(!flag){
            cont++;
         }else if(v[i] == 1 && flag){
            flag = 0;
            cont++;
         }
      }
      for(int i = n-1; i>=0;i--){
         if(v[i] == 0){
            cont--;
         }else{
            break;
         }
      }
      if(cont <= k) cout<<"YES"<<endl;
      else cout<<"NO"<<endl;
   }
   return 0;
}

