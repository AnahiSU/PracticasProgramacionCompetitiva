#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n,x; cin>>n>>x;

   vector<int>v(n);
   int res = 0;
   int mulTot = 1;
   for(int i = 0; i<n;i++){
      cin>>v[i];
      res+=(int)(x/v[i]);
      mulTot*=v[i];
   }

   int sum = 0;
   for(int i = 0; i<n;i++){
      for(int j = i+1; j<n;j++){
         sum+= (int)(x/(v[i]*v[j]));
      }
   }
   if(n==1){
      res = x/v[0];
   }else if(n==2){
      res-=(int)(x/mulTot);
   }else{
      sum-=(int)(x/mulTot);
      res-=sum;
   }
   cout<<res<<endl;
   
   return 0;
}

