using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int n; cin>>n;
	int salt[] = {5,4,3,2,1};
	int c = 0;
	for(int i = 0; i<5;i++){
		if(n>=salt[i]){
			int res = n/salt[i];
			c+=res;
			n-=res*salt[i];
		}
	}
	cout<<c<<endl;
    return 0;
}

