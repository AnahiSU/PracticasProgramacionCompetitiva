using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int n; cin>>n;

	string s; cin>>s;	
	int i = 0,cont=0, cups = 0;
	while(i<n){
		if(s[i] == '1'){
			i++;
			cups=2;
		}else{	
			if(cups <= 0){
				cont++;
			}
			cups--;
			i++;
		}
	}
	cout<<n-cont<<endl;
    return 0;
}

