#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      vector<int>dg(n);
      for(int i = 0; i<n-1;i++){
         int a,b; cin>>a>>b;
         dg[a-1]++;
         dg[b-1]++;
      }
      int cont = 0;
      for(int i : dg){
         if(i==1)cont++;
      }
      int res = cont/2;
      if(cont&1)res++;
      cout<<res<<endl;
   }
   return 0;
}

