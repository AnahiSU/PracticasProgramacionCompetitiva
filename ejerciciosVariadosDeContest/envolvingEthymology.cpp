using namespace std;
int binpow(int a, int b, int n) {
    int res = 1;
    a = a % n; 
    while (b > 0) {
        if (b & 1)
            res = (res * a) % n;  
        
        a = (a * a) % n;
        b >>= 1;
    }
    return res;
}

signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n, k; cin>>n>>k;
   string s; cin>>s;
   string res = s;
   for(int i = 0; i<n;i++){
      res[i] = s[(i*binpow(2,k,n))%n];
   }
   cout<<res<<endl;
   return 0;
}

