#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      string s; cin>>s;
      int n = sz(s);
      vector<int>v(n);
      for(int i = 0; i<n;i++){
         v[i] = s[i] == '(' ? 0:1;
      }
      int op = 1, cont = 0;
      for(int i = 1; i<n;i++){
         if(v[i] == 1){
            op--;
         }else{
            op++;
         }
         if(op == 0){
            cont++;
         }
      }
      if(cont > 1){
         cout<<"YES"<<endl;
      }else{
         cout<<"NO"<<endl;
      }
   }
   return 0;
}

