#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n;
   while(cin>>n && n){
      vector<int>v(n);
      for(int i = 0; i<n;i++) cin>>v[i];
      sort(v.rbegin(),v.rend());
      int cont = 1;
      for(int i = 0; i<n;i++){
         if(v[i]>=cont){
            cont++;
         }else{
            break;
         }
      }
      cout<<cont-1<<endl;
   }
   return 0;
}

