#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      vector<int>v(n);
      for(int i = 0; i<n;i++) cin>>v[i];
      set<int>ls;
      for(int i = 0; i<n;i++){
         auto ptr = ls.find(v[i]-1);
         if(ptr!=ls.end()){
            ls.erase(ptr);
            ls.insert(v[i]);
         }else{
            ls.insert(v[i]);
         }
      }
      cout<<sz(ls)-1<<endl;
   }
   return 0;
}

