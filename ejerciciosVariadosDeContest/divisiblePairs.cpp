#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n,x,y; cin>>n>>x>>y;
      vector<int>v(n);
      map<pair<int,int>,int>ls;
      for(int i = 0; i<n;i++){
         cin>>v[i];
         ls[{v[i]%x , v[i]%y}]++;
      }
      int res = 0;
      for(int i = 0; i<n;i++){
         ls[{v[i]%x, v[i]%y}]--;
         res += ls[{(x-v[i]%x)%x , v[i]%y}];
      }
      cout<<res<<endl;
   }
   return 0;
}

