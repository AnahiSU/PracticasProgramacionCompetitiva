#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      vector<int>v(n);
      for(int i = 0 ; i<n;i++){
         cin>>v[i];
      }
      vector<int>maxim(n);
      int ant = -1;
      for(int i = 0; i<n;i++){
         maxim[i] = max(ant,v[i]);
         ant = maxim[i];
      }
      vector<int>res(n);
      vector<int>sum(n);
      sum[n-1] = v[n-1];
      for(int i = n-2; i>=0;i--){
         sum[i] = sum[i+1]+v[i];
      }
      res[0] = maxim[n-1];

      for(int i = 1; i<n;i++){
         res[i] = maxim[n-i-1] + sum[n-i];
      }
      for(int i : res){
         cout<<i<<" ";
      }
      cout<<endl;
   }
   return 0;
}

