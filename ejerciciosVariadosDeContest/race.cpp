signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int a,x,y; cin>>a>>x>>y;
      int d1 = abs(a-x);
      int d2 = abs(a-y);
      bool flag = 0;
      for(int i = 0; i<200;i++){
         int num = i+1;
         if(num == a){
            continue;
         }else{
            int dis1 = abs(num-x);
            int dis2 = abs(num-y);
            if(dis1 < d1 && dis2 < d2){
               break;
            }
         }
      } 
      if(flag) cout<<"YES"<<endl;
      else cout<<"NO"<<endl;
   }
   return 0;
}

