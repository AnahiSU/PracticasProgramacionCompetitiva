typedef long long ll;
#define srt(a) sort(a.begin(),a.end());
#include <bits/stdc++.h>
#define int long long

using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){
		string s; cin>>s;
		int n = (int)s.size();
		int sum = 0,dos=0,tres=0;
		for(int i = 0; i<n;i++){
			sum+=s[i]-'0';
			if(s[i] == '2') dos++;
			if(s[i] == '3') tres++;
		}
		bool flag = false;
		if(sum %9 == 0) flag = true;
		if(!flag){
			for(int i = 0; i<=min(10LL,dos);i++){
				for(int j = 0; j<=min(10LL,tres);j++){
					if((sum + i*2 + j*6) % 9 == 0){ flag = true;break;}
				}
			}
		}

		if(flag) cout<<"YES"<<endl;
		else cout<<"NO"<<endl;

	}
    return 0;
}

