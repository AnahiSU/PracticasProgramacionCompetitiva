signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int n,m;
	cin>>n>>m;
	multiset<int>v;
	for(int i = 0; i<n;i++){
		int x;
		cin>>x;v.insert(x);
	}
	while(m--){
		int x; cin>>x;
		auto it = v.upper_bound(x);
		if(it!=v.begin()){
			cout<<*(--it)<<endl;
			v.erase(it);
		}else{
			cout<<-1<<endl;
		}
	}
    return 0;
}

