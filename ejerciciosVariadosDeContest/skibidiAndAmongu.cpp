signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){
		string s; cin>>s;
		int n = (int)s.size();
		if(n == 1){
			cout<<'i'<<endl;
		}else{
			if(s[n-2]=='u'){
				string aux = s.substr(0,n-2);
				aux.push_back('i');
				cout<<aux<<endl;
			}else{
				string aux = s.substr(0,n-1);
				aux.push_back('i');
				cout<<aux<<endl;
			}
		}
	}
    return 0;
}

