#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n,a,b; cin>>n>>a>>b;
   string s; cin>>s;
   int passedTot =0, passedOv = 0;
   for(int i = 0; i<n;i++){
      if(s[i] == 'a'){
         if(passedTot < a+b){
            passedTot++;
            cout<<"Yes"<<endl;
         }else{
            cout<<"No"<<endl;
         }
      }else if(s[i]=='b'){
         if(passedTot < a+b && passedOv<b){
            passedOv++;
            passedTot++;
            cout<<"Yes"<<endl;
         }else{
            cout<<"No"<<endl;
         }
      }else{
         cout<<"No"<<endl;
      }
   }
   return 0;
}

