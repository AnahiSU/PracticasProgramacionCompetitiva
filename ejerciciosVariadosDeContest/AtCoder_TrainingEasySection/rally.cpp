#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n; cin>>n;
   int maxi = -1;
   vector<int>v(n);
   for(int i = 0; i<n;i++){
      cin>>v[i];
      maxi = max(v[i],maxi);
   }

   int res = 1e18;
   for(int i = 0; i<=maxi;i++){
      int aux = 0;
      for(int j = 0; j<n;j++){
         aux+= abs(v[j]-i) * abs(v[j]-i);
      }
      res = min(res,aux);
   }

   cout<<res<<endl;
   return 0;
}

