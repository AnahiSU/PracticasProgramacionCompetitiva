#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n,k; cin>>n>>k;
      vector<pair<pair<int,int>,int>> v(n);
      for(int i = 0; i<n;i++){
         int a,b,c; cin>>a>>b>>c;
         v[i] = {{a,b},c};
      }
      srt(v);
      for(int i = 0; i<n;i++){
         if(v[i].first.first <= k && v[i].first.second >= k && v[i].second >= k){
            k = v[i].second;
         }
      }
      cout<<k<<endl;
   }
   return 0;
}

