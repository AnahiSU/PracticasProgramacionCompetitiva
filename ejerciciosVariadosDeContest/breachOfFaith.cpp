#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      vector<int>v(2*n);
      for(int i =0; i<2*n;i++){
         cin>>v[i];
      }
      sort(v.rbegin(),v.rend());


      int sum = 0;
      vector<int>res(2*n+1);
      int j = 0;
      for(int i = 0; i<2*n+1;i+=2){
         res[i] = v[j];
         j++;
         sum += res[i];
      } 
      j = 2*n-1; 
      for(int i = 1;i<2*n+1;i+=2){
         if(i==2*n-1) break;
         res[i] = v[j];
         j--;
         sum -= res[i];
         
      }
      res[2*n-1] = sum;
      for(int i : res){
         cout<<i<<' '; 
      }
      cout<<endl;
   }
   return 0;
}

