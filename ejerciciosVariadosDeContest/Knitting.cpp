typedef long long ll;
#define srt(a) sort(a.begin(),a.end());
#include <bits/stdc++.h>


using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	ll n, p;
	cin >> n >> p;
	if (n % p == 0) {
		cout << 0 << '\n';
		return 0;
	}
	ll rem = (n - p) / 2;
	ll ans = rem % p;
	cout << ans * 2 << '\n';
    return 0;
}

