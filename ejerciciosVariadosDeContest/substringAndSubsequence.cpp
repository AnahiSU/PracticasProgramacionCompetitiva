#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      string a,b; cin>>a>>b;
      int n = sz(a);
      int m = sz(b);
      int res = 2e9;
      for(int i = 0; i<m;i++){
         int k = i;
         for(int j= 0; j<n && k<m;j++){
            if(b[k] == a[j]){
               k++;
            }
         }
         res = min(res, n+m-(k-i));
      }

      cout<<res<<endl;
   }
   return 0;
}

