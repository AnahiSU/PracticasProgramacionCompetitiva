#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n; cin>>n;
   vector<string>v(n);
   for(int i = 0; i<n;i++) cin>>v[i];
   int res = -1;

   for(int i = 0; i<sz(v[0]) && res == -1;i++){
      char ant = v[0][i];
      
      for(int j = 0; j<n && res == -1; j++){
         if(v[j][i] != ant){
            res = i;
            break;
         }
      }
   }
   cout<<res<<endl;
   return 0;
}

