#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      vector<int>v(n);
      map<int,int>ls;
      for(int i = 0; i<n;i++){ cin>>v[i]; ls[v[i]]++;}
      int cont = 1;
      set<int>visi;
      set<int>seg;
      seg.insert(v[0]);
      for(int i = 1; i<n;i++){
         visi.insert(v[i]);

         auto punt  = seg.find(v[i]);
         if(punt != seg.end()){
            //encontre
            seg.erase(punt);
         }
         if(seg.empty()){
            cont++;
            seg = visi;
            visi.clear();
         }
      }
      cout<<cont<<endl;

   }
   return 0;
}

