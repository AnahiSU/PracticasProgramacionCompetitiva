#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n; cin>>n;
   vector<int>v(n-1);
   for(int i = 0; i<n-1;i++) cin>>v[i];
   for(int i = 0; i<n-1;i++){
      int sum = v[i];
      cout<<sum<<' ';
      for(int j = i+1; j<n-1;j++){
         sum+=v[j];
         cout<<sum<<' ';
      }
      cout<<endl;
   }
   return 0;
}

