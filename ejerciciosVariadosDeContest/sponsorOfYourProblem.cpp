#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      string s1,s2; cin>>s1>>s2;
      int n = sz(s2);
      if(s1 == s2){
         cout<<n*2<<endl;
         continue;
      }
      int cont = 0;
      for(int i = 0; i<n;i++){
         if(s1[i] == s2[i]){
            cont++;
         }else{
            break;
         }
      }
      int res = cont*2;

      if(s2[cont] - s1[cont] == 1){
         res++;
         for(int i = cont+1; i<n;i++){
            if(s1[i] == '9' && s2[i] =='0') res++;
            else break;
         }
      } 
      
      cout<<res<<endl;

   }
   return 0;
}

