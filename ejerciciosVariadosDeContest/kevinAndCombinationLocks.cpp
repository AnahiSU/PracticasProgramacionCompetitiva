typedef long long ll;
#define srt(a) sort(a.begin(),a.end());
#include <bits/stdc++.h>


using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){
		int n; cin>>n;
		while(true){
			string s = to_string(n);
			if(n==33 || n == 0){
				cout<<"YES"<<endl;
				break;
			}
			if(n<33){
				cout<<"NO"<<endl;
				break;
			}
			int ind = s.find("33");
			if(ind == -1){
				if(n%33==0){
					cout<<"YES"<<endl;;
					break;
				}else{
					cout<<"NO"<<endl;
					break;
				}
			}else{
				string aux = s.substr(0,ind);
				aux = aux+s.substr(ind+2);
				s = aux;
				n = stoi(s);
			}

		}

	}
    return 0;
}

