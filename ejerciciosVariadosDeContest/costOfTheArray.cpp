signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){
		int n,k; cin>>n>>k;
		vector<int>a(n+1);

		for(int i=1;i<=n;i++){
			cin>>a[i];
		}

		if(n==k){
			int res = 0;
			for(int i =2; i<=n;i+=2){
				if(a[i] ==i/2){
					res = i/2;
				}else{
					break;
				}
			}
			cout<<res+1<<endl;
		}else{
			bool flag = 0;
			for(int i =2; i<=n-k+2;i++){
				if(a[i] != 1) flag =1;
			}
			if(flag) cout<<1<<endl;
			else cout<<2<<endl;
		}
	}
    return 0;
}

