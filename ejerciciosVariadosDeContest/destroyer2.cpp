typedef long long ll;
#define srt(a) sort(a.begin(),a.end());
#include <bits/stdc++.h>


using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){
		int n; cin>>n;
		vector<int>v(101);
		int maxi = 0;
		for(int i = 0; i<n;i++){
			int x;
			cin>>x;
			v[x]++;
			maxi = max(maxi,x);
		}
		bool flag = true;
		for(int i = 0; i<maxi;i++){
			if(i==0 && v[i] == 0){
				flag = false;
				break;
			}
			if(v[i]<v[i+1]){
				flag = false;
				break;
			}
		}
		if(flag) cout<<"YES"<<endl;
		else cout<<"NO"<<endl;
	}
    return 0;
}

