using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){
		string s; cin>>s;
		int n = s.size();
		for(int i = n-1; i>=0;i--){
			if(s[i] == 'p') cout<<'q';
			if(s[i] == 'q') cout<<'p';
			if(s[i] == 'w') cout<<'w';
		}
		cout<<endl;
	}
    return 0;
}

