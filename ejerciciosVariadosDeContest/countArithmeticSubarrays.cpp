#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n; cin>>n;
   vector<int>v(n);
   for(int i = 0; i<n;i++) cin>>v[i];
   vector<int>d;
   for(int i = 1; i<n;i++){
      d.push_back(abs(v[i]-v[i-1]));
   }

   int cont = 1, res = 0;
   for(int i = 0; i<sz(d)-1;i++){
      if(d[i] == d[i+1]){
         cont++;
      }else{
         res+= (cont*(cont+1))/2;
         cont = 1;
      }
   }
   if(cont){
      res+= (cont*(cont+1)/2);
   }
   if(n!=1)cout<<res+n<<endl;
   else cout<<1<<endl;

   return 0;
}

