using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){

		int n; cin>>n;
		vector<int>v(n);
		int c1=0,c2=0,sum1=0,sum2=0;
		for(int i = 0; i<n;i++){
			cin>>v[i];
		}
		for( int i = 0; i<n;i++){
			if(i%2==0){
				c1++;
				sum1+=v[i];
			}else{
				c2++;
				sum2+=v[i];
			}
		}
		if(sum1%c1==0 && sum2%c2==0 &&(sum1/c1) == (sum2/c2)){
			cout<<"YES"<<endl;
		}else{
			cout<<"NO"<<endl;
		}
	}
    return 0;
}

