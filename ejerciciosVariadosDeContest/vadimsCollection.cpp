using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      string s; cin>>s;
      int n = 10;
      vector<int>res(n);
      for(int i = 0; i<n; i++){
         int found = -1;
         int x = 10-i-1;
         while(found == -1){
            for(int j = 0; j<n;j++){
               if(s[j]-'0' == x){
                  found = s[j]-'0';
                  s[j] = '$';
                  break;

               }
            }
            x++;
         }
         res[i] = found;
      } 
      for(int i : res){
         cout<<i;
      }
      cout<<endl;
   }
   return 0;
}

