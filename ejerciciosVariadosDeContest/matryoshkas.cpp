#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      map<int,int>ls;
      for(int i = 0; i<n;i++){
         int x;cin>>x;
         ls[x]++;
      }
      vector<pair<int,int>>v;
      for(auto i : ls){
         v.push_back({i.first , i.second});
      }

      int res = 1;
      for(int i = 1; i<sz(v); i++){
         if(v[i-1].second < v[i].second){
            res+=abs(v[i-1].second - v[i].second);
         }else if(v[i].first - v[i-1].first != 1){
            res+=abs(v[i-1].second - v[i].second);
         }
      }
      if(sz(v)==1) cout<<v[0].second<<endl;
      else cout<<res<<endl;
   }
   return 0;
}

