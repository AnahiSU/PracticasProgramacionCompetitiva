using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n;
   while(cin>>n){
      vector<int>v(n);
      for(int i = 0; i<n;i++) cin>>v[i];
      
      vector<int>v2;
      for(int i = 0; i<n;i++){
         v2.push_back(v[i]/(i+1));
      }
      int mini = *min_element(v2.begin(),v2.end());
      if(mini % 2 == 0){
         cout<<"N"<<endl;
      }else{
         cout<<"S"<<endl;
      }
   }
   
   return 0;
}

