#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n,m; cin>>n>>m;
   vector<int>v(n),ls(m+1);

   for(int i = 0; i<n;i++){
      cin>>v[i];
   }

   srt(v);
   int i =0, j = 1;
   while(i<n && j<m+1){
      if(v[i]<= j){
         ls[j]++;
         i++;
      }else{
         j++;
         //ls[j]++;
         
      }
       
   }

   for(int k = m-1; k>=0; k--){
      ls[k] += ls[k+1];
   }
   for(int k = 1; k<m+1; k++){
      cout<<ls[k]<<' ';
   }
   cout<<endl;


   return 0;
}

