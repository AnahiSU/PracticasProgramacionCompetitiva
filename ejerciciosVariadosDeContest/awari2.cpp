#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n;
   while(cin>>n && n!=-1){
      vector<int>v(n);
      for(int i = 0; i<n;i++) cin>>v[i];

      int res = v[0];
      for(int i = 1; i<n;i++){
         if(v[i])res^=v[i];
      }
      if(res) cout<<'S'<<endl;
      else cout<<'N'<<endl;
   }
   return 0;
}

