using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	string s; cin>>s;
	vector<int>v(4);
	int n = (int)s.size();
	for( int i = 0; i<n;i++){
		if(s[i] == 'A') v[0]++;
		if(s[i] == 'L') v[1]++;
		if(s[i] == 'P') v[2]++;
		if(s[i] == 'C') v[3]++;
	}
	int mini = 1e9;
	v[0] /= 3;
	for( int i =0; i<4;i++){
		mini = min(mini,v[i]);
	}
	cout<<mini<<endl;
    return 0;
}

