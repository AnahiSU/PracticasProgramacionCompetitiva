#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      vector<int>v(n);
      if(!(n&1)){
         cout<<-1<<endl;
         continue;
      }
      int cont = n - (n/2); 
      for(int i = 0; i<n; i++){
         v[i] = (i+1 + (cont%n))%n;
         if(v[i] == 0) v[i] = n;
         cont++;
      }
      for(int i : v){
         cout<<i<<" ";
      }
      cout<<endl;
   }
   return 0;
}

