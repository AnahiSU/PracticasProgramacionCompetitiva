using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int x; cin>>x;
   while(x--){
      int n,m,l,r; cin>>n>>m>>l>>r;
      if(l==0){
         cout<<0<<' '<<m<<endl;
      }else if(r==0){
         cout<<-m<<' '<<0<<endl;
      }else{
      
         if(r<m){
            m = m-r;
         }else{
            r = m;
            m = 0;
         }

         l = -m;
         cout<<l<<' '<<r<<endl;
      } 
   }
   return 0;
}

