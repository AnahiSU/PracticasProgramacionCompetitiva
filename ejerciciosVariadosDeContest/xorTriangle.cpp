signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      int num = -1;
      bool flag = 1;
      for(int i = 0; i<30 && flag;i++){
         for(int j = 0; j<30 && flag;j++){
            int prob = (1<<i) | (1<<j);
            int x = prob^n;
            if(x + n > prob && prob + x > n && n+prob >x && prob < n){
               num = prob;
               flag = 0;
            }
         
         }
      }
      cout<<num<<endl;
   }
      
   
   return 0;
}

