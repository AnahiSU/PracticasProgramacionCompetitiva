#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   string s; cin>>s;
   vector<int>visi(28);
   string res = "";
   for(int i = 0; i<sz(s);i++){
      if(!visi[s[i]- 'a']){
         res.push_back(s[i]);
         visi[s[i]-'a'] = 1;
      }else{
         break;
      }
   }
   cout<<res<<endl;
   return 0;
}

