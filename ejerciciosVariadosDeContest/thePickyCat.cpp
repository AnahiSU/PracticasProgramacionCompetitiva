#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      int mid = (n&1) ? n/2 : (n/2) -1;
      vector<int>v(n);
      for(int i = 0 ; i<n;i++) cin>>v[i];
      vector<int> ab(n);
      for(int i = 0;i<n;i++){
         ab[i] = abs(v[i]);
      }
      int piv = v[0];
      srt(v); srt(ab);
      if(v[mid] == piv){
         cout<<"YES"<<endl;
      }else{
         int ind =0;
         for(int i = 0; i<n;i++){
            if(ab[i] == abs(piv)){
               ind= i; break;
            }
         }
         
         if(n-ind-1 >= mid){
            cout<<"YES"<<endl;
         }else{
            cout<<"NO"<<endl;
         }
      }
      
   }
   return 0;
}

