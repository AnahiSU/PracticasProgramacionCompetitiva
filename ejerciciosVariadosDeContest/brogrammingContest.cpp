using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){
		int n; cin>>n;
		string s;
		cin>>s;
		int cont =1;
		for(int i = 1;i<n;i++){
			if(s[i-1]!=s[i]){
				cont++;
			}
		}
		
		if(s[0]=='1') cout<<cont<<endl;
		else cout<<cont-1<<endl;
	}
    return 0;
}

