#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n; cin>>n;
      vector<int>v(n);
      for(int i = 0; i<n;i++) cin>>v[i];
      int sum = 0, mini = 1e18;
      srt(v);
      int cont = 0;
      for(int i : v){
         sum+=i;
         mini = min(mini,i);
      }
      for(int i : v){
         if(i==mini) cont++;
      }
      if(mini == 0) sum+=cont;
      cout<<sum<<endl;
   }
   return 0;
}

