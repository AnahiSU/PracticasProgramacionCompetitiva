using namespace std;

int piso(int x, int n){
   while((n--) && x){
      x = x>>1;
   }
   return x;
}

int techo(int x,int m){
   while(m-- && x>1){
      x = (x+1)>>1;
   }
   return x;
}

signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int x,n,m; cin>>x>>n>>m;
      cout<<piso(techo(x,m),n)<<' '<<techo(piso(x,n),m)<<endl;
   }
   return 0;
}

