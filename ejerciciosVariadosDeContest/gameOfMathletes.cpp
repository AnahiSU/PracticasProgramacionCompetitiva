#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   while(c--){
      int n,k; cin>>n>>k;
      vector<int>v(n);
      for(int i = 0; i<n;i++) cin>>v[i];
      srt(v);
      int i=0,j=n-1,cont=0;
      while(i<j){
         int sum = v[i]+v[j];
         if(sum == k){
            cont++;
            i++;
            j--;
         }else if(sum < k){
            i++;
         }else{
            j--;
         }
      }
      cout<<cont<<endl;
   }
   return 0;
}

