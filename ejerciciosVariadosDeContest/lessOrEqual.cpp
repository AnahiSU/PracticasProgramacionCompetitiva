#define srt(a) sort(a.begin(),a.end());
#include <bits/stdc++.h>
#define int long long

using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int n,k; cin>>n>>k;
	vector<int>v(n);
	for(int i =0;i<n;i++){
		cin>>v[i];
	}
	srt(v);
	if(k>n){
		cout<<-1<<endl;
	}else{
		if(!k){
			if(v[0]==1) cout<<-1<<endl;
			else cout<<v[0]-1<<endl;
		}else{ 
			if(n==1){
				cout<<v[0]<<endl;
			}else{
				if(v[k]==v[k-1]){
					cout<<-1<<endl;
				}else{
					cout<<v[k-1]<<endl;
				}
			}
		}
	}
    return 0;
}

