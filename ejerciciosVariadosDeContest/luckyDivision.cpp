using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	vector<int>lucky;
	for(int i = 4; i<=777;i++){
		int num = i;
		bool flag = true;
		while(num>0){
			if(num%10 != 4 && num%10 != 7){
				flag = false;
				break;
			}
			num /=10;
		}
		if(flag) lucky.push_back(i);
	}

	int n; cin>>n;
	bool flag = false;
	for(int i = 0; i<lucky.size();i++){
		if(n%lucky[i] == 0){
			flag = true;
			break;
		}
	}
	if(flag) cout<<"YES"<<endl;
	else cout<<"NO"<<endl;
    return 0;
}

