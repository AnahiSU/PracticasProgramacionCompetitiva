typedef long long ll;
#define srt(a) sort(a.begin(),a.end());
#include <bits/stdc++.h>


using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	string s; cin>>s;
	int n = (int)s.size();
	vector<int>v;
	for( int i = 0; i<n;i++){
		if(s[i]!='+'){
			v.push_back(s[i]-'0');
		}
	}
	srt(v);
	for(int i = 0; i<(int)v.size();i++){
		if(i == (int)v.size()-1) cout<<v[i]<<endl;
		else cout<<v[i]<<"+";
	}

    return 0;
}

