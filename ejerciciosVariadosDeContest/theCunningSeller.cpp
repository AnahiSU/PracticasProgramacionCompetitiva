#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;
long long binpow(long long a, long long b) {
    long long res = 1;
    while (b > 0) {
        if (b & 1)
            res = res * a;
        a = a * a;
        b >>= 1;
    }
    return res;
}

map<int,int>prec;
void preproc(){
   for(int pot = 0; pot<22;pot++){
      int ben = binpow(3LL,pot+1) + pot * binpow(3LL,pot-1);
      prec[binpow(3LL,pot)] = ben;
   }
}

signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c; cin>>c;
   preproc();
   
   while(c--){
      int n; cin>>n;
      int res = 0;
      while(n>0){
         int potM = 0;
         for(auto i : prec){
            if(i.first > n){
               potM  = i.first/3;
               break;
            }
         }
         res+=prec[potM];
         n-=potM;
      }
      cout<<res<<endl;

   }
   return 0;
}

