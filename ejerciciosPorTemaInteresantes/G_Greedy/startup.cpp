#include <bits/stdc++.h>
#define int long long

using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){
		int s,k; cin>>s>>k;
		map<int,int>ls;
		for(int i = 0; i<k;i++){
			int b,c; cin>>b>>c;
			ls[b]+=c;
		}
		vector<int>v;
		for(auto i:ls){
			v.push_back(i.second);

		}
		int i = 0;
		sort(v.rbegin(),v.rend());
		int sum =0 ;	
		while(i<(int)v.size() && s){
			sum+=v[i];
			s--;
			i++;
		}

		cout<<sum<<endl;

	}
    return 0;
}

