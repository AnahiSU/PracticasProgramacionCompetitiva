#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n,q; cin>>n>>q;
   vector<int>v(n), sums(n+1);
   for(int i = 0; i<n;i++) cin>>v[i];
   for(int i = 1; i<n+1;i++){
      sums[i] = sums[i-1]+v[i-1];
   }
   while(q--){
      int a,b; cin>>a>>b; a--;b--;
   
      cout<<sums[b] - sums[a-1]<<endl;
   }
   return 0;
}

