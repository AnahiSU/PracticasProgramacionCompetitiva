#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n; cin>>n;
   vector<string>v(n);
   cin.ignore();

   for(int i = 0; i<n; i++){
      getline(cin,v[i]);
   }

   vector<pair<string,string>>v2(n);
   for(int i = 0; i<n; i++){
      for(int j = 0; j<sz(v[i]);j++){
         if(v[i][j] >= 65 && v[i][j]<=90){
            v2[i] = {v[i].substr(j,sz(v[i])-j),v[i]};
            break;
         }
      }
   }
   srt(v2);
   for(auto i : v2){
      cout<<i.second<<endl;
   }
   return 0;
}

