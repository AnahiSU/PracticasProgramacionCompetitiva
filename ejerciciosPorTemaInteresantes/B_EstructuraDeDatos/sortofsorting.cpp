using namespace std;

bool cmp (string a, string b){
   string aux1 = a.substr(0,2);
   string aux2 = b.substr(0,2);
   return aux1<aux2;
}

signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c;
   
   while(cin>>c && c){
      vector<string>v(c);
      for(int i = 0; i<c;i++) cin>>v[i];

      stable_sort(v.begin(),v.end(),cmp);
      for(auto s: v){
         cout<<s<<endl;
      }
      cout<<endl;
   }
   return 0;
}

