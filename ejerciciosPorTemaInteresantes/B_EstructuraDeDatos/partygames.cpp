#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int c;
   while(cin>>c && c){
      vector<string>v(c);
      for(int i = 0; i<c; i++) cin>>v[i];

      srt(v);
      string s2 = v[c/2];
      string s1 = v[(c/2)-1];
      string res = "";
      for(int i = 0; i<sz(s1); i++){
         char aux = s1[i]+1;
         res.push_back(aux);
         if(res >= s1 && res < s2 && res.back()<='Z'){
            break;
         }else{
            res[sz(res)-1]--;
         }
      }
      res[sz(res)-1]--;
      if(!(s1<=res && s2 > res)) res[sz(res)-1]++;

      cout<<res<<endl;
   }
   return 0;
}

