#define srt(a) sort(a.begin(),a.end());
#include <bits/stdc++.h>
#define int long long

using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int x;
	vector<int>v;
	while(cin>>x){
		v.push_back(x);
		int n = v.size();
		srt(v);
		if(n%2==0){
			cout<<(v[n/2] + v[(n/2)-1])/2<<endl;
		}else{
			cout<<v[n/2]<<endl;
		}
	}
    return 0;
}

