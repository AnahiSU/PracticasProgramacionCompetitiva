#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;

signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n;
   while(cin>>n && n){
      vector<pair<double,int>>v(n);
      for(int i = 0;i<n; i++){
         int a,b,c; cin>>a>>b>>c;
         double dw = 10.0-(10.0/(2.0*c));
         v[i] = {dw, a*b*c};
      }
      srt(v);
      cout<<v[n-1].second<<endl;
   }
   return 0;
}

