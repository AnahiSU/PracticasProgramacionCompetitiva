using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	string s,res; cin>>s;
	for( int  i = 0; i<(int)s.size();i++){
		char aux = s[i];
		aux = tolower(aux);
		if(aux != 'a' && aux!='e' && aux!='i' && aux!='o' && aux!='u'&& aux!='y'){
			res.push_back('.');
			res.push_back(aux);
		}
	}
	cout<<res<<endl;
    return 0;
}

