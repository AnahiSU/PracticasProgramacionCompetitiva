using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	while(c--){
		string s,t; cin>>s>>t;
		int i = 0,cont=0;
		int j = 0;
		while(i< (int)s.size() && j<(int)s.size() && s[i] == t[j]){
			cont++;
			j++;i++;
		}
		if(j != 0 && i != 0)cont++;
		if(i == (int)s.size()){
			cont+=(int)t.size()-j;
		}else if(j == (int)t.size()){
			cont+=(int)s.size()-i;
		}else{
			cont+= (int)s.size()-i + (int)t.size()-j;
		}
		cout<<cont<<endl;

	}



    return 0;
}

