#include <bits/stdc++.h>


using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int n,k; cin>>n>>k;
	vector<vector<int>>v(n,vector<int>(k,0));
	for(int i = 0; i<n;i++){
		int hor; cin>>hor;
		for(int j = 0; j<hor;j++){
			int x; cin>>x;
			x--;
			v[i][x] = 1;
		}
		
	}
	int c = 0;
	for(int i = 0; i<k;i++){
		int sum = 0;
		for(int j = 0; j<n;j++){
			sum+=v[j][i];
		}
	 	if(sum>=1) c++;
	}
	if(c>=n) cout<<n<<endl;
	else cout<< c <<endl;

    return 0;
}

