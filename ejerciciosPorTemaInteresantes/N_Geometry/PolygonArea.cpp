struct point {
  double x, y;
  point() {x = y = 0.0;}
  point(double _x, double _y) : x(_x), y(_y) {}
};

double area(const vector<point>& fig) {
    double res = 0;
    for (unsigned i = 0; i < fig.size(); i++) {
        point p = i ? fig[i - 1] : fig.back();
        point q = fig[i];
        res += (p.x - q.x) * (p.y + q.y);
    }
    return abs(res);
}

