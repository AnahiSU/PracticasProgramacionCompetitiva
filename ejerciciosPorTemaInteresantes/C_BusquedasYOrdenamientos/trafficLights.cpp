using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int x,n; cin>>x>>n;
   multiset<int>cuts,lens;
   cuts.insert(0);
   cuts.insert(x);
   lens.insert(x);
   /*
   for(int i : cuts) cout<<i<<' ';
   cout<<endl;
   */
   for(int i = 0; i<n;i++){
      int a; cin>>a;
      auto ptr = cuts.lower_bound(a);
      auto ptr2 = prev(ptr);
      //cout<<*ptr<<endl;
      
      int newL = a - (*ptr2);
      int newC = (*ptr2) + newL;
      
      lens.erase(lens.find((*ptr) - (*ptr2)));
      lens.insert((*ptr) - a);
      lens.insert(a - (*ptr2));

      cuts.insert(newC);

      cout<<*(--(lens.end()))<<' ';

   }
   return 0;
}

