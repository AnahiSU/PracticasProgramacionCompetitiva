#include <bits/stdc++.h>

using namespace std;

long long compute_hash(string const& s) {
    const int p = 31;
    const int m = 1e9 + 9;
    long long hash_value = 0;
    long long p_pow = 1;
    for (char c : s) {
        hash_value = (hash_value + (c - 'a' + 1) * p_pow) % m;
        p_pow = (p_pow * p) % m;
    }
    return hash_value;
}
signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c; cin>>c;
	set<long long> hashes;
	while(c--){
		string s;
		cin>>s;
		long long h = compute_hash(s);
		hashes.insert(h);
	}
	cout<<hashes.size();
    return 0;
}

