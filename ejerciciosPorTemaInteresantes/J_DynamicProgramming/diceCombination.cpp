#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;
int MOD = 1e9+7;

signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n; cin>>n;
   vector<int>dp(n+1);
   dp[0] = 1;
   for(int i = 1; i<n+1;i++){
      for(int j = 1; j<7;j++){
         if(i-j >= 0){
            dp[i] += dp[i-j] %MOD;
            dp[i] %=MOD;
         }
      }
   }
   cout<<dp[n]<<endl;
   return 0;
}

