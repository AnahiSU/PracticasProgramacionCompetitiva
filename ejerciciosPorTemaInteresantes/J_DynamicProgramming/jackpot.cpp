using namespace std;
int n;
vector<int> v,dp;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	
	while(cin>>n && n){
		v.resize(n);
		int suma = 0,resp = -1e9;
		for(int i = 0; i<n;i++){
			cin>>v[i];
			suma += v[i];
			if(suma>resp){
				resp = suma;
			}
			if(suma<0){
				suma = 0;
			}
		}
		if(resp>0){
			cout<<"The maximum winning streak is "<<resp<<".";
		}else{
			cout<<"Losing streak.";
		}
		cout  	<<endl;
	}

    return 0;
}

