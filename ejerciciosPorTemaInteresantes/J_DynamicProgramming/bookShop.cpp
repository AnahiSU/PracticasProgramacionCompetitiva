#define srt(a) sort(a.begin(),a.end())
#include <bits/stdc++.h>
#define endl "\n"
#define int long long
#define sz(v) (int)v.size()

using namespace std;


signed main (){
   std::ios::sync_with_stdio(false);cin.tie(0);
   int n,x; cin>>n>>x;
   vector<int>pag(n),prec(n),dp(x+1);
   for(int i = 0; i<n;i++) cin>>prec[i];
   for(int i = 0; i<n;i++) cin>>pag[i];

   for(int i = 0; i<n;i++){
      for(int j = x; j>= prec[i]; j--){
         dp[j] = max(dp[j],dp[j-prec[i]] + pag[i]);
      }
   }
   cout<<dp[x]<<endl;
   return 0;
}

