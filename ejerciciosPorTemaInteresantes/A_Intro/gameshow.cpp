using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c = 100;
	int n; cin>>n;
	vector<int> nums(n);
	for(int i= 0; i < n; i++){
		cin>>nums[i];
	}
	
	int res = c;
	
	for(auto i : nums){
		c += i;
		res = max(res,c);
	}
	cout<<res<<endl;
    return 0;
}

