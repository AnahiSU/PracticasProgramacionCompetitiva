using namespace std;


signed main (){
	std::ios::sync_with_stdio(false);cin.tie(0);
	int c;cin>>c;
	vector<int>prep(231,-1);
	while(c--){
		int n,q; cin>>n>>q;
		vector<int>v(n);
		for(int i = 0; i<n; i++){
			cin>>v[i];
		}
		for(int i = 0;i<231;i++){
			for(int j = 0; j<n; j++){
				prep[i] = max(prep[i],i&v[j]);
			}
		}
		for(int i = 0; i<q;i++){
			int a; cin>>a;
			cout<<prep[a]<<endl;

		}
	}
    return 0;
}

